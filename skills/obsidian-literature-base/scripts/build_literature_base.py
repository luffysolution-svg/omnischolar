import json
import os
import re
import sys
import unicodedata
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from urllib.parse import unquote

import yaml

GENERATED_BY = "obsidian-literature-base"
BASE_MARKER = f"# Generated by {GENERATED_BY}; manual edits may be overwritten."
MARKDOWN_MARKER = f"generatedBy: {GENERATED_BY}"
GENERATED_COMMENT = f"<!-- Generated by {GENERATED_BY}; manual edits may be overwritten. -->"
MANUAL_START = "<!-- MANUAL:START -->"
MANUAL_END = "<!-- MANUAL:END -->"
AUTO_START = "<!-- AUTO:START -->"
AUTO_END = "<!-- AUTO:END -->"
DEFAULT_TOPIC_PREFIXES = ("topic/", "主题/")
IMAGE_SUFFIXES = {".avif", ".gif", ".jpeg", ".jpg", ".png", ".svg", ".webp"}
MAX_MARKDOWN_BYTES = 64 * 1024 * 1024
STANDARD_IMAGE_RE = re.compile(r"!\[[^\]]*\]\(([^)]+)\)")
WIKI_IMAGE_RE = re.compile(r"!\[\[([^\]|]+)(?:\|[^\]]+)?\]\]")


@dataclass(slots=True)
class PaperPlan:
    directory: Path
    sidecar: dict[str, Any]
    markdown_path: Path
    source_properties: dict[str, Any]
    zotero_record: Path | None
    images: list[str]
    topics: list[str]
    topic_source: str
    title: str
    index_path: Path


def _confined(root: Path, relative: str) -> Path:
    candidate = (root / relative).resolve()
    try:
        candidate.relative_to(root)
    except ValueError as exc:
        raise ValueError(f"Path escapes the vault root: {relative}") from exc
    return candidate


def _read_json(path: Path) -> dict[str, Any]:
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError(f"Expected a JSON object: {path}")
    return value


def _frontmatter(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8", errors="replace") as handle:
        if handle.readline().strip() != "---":
            return {}
        lines: list[str] = []
        size = 0
        for line in handle:
            size += len(line.encode("utf-8"))
            if size > 256 * 1024:
                return {}
            if line.strip() == "---":
                value = yaml.safe_load("".join(lines)) or {}
                return value if isinstance(value, dict) else {}
            lines.append(line)
    return {}


def _publication_sidecars(vault_root: Path) -> list[tuple[Path, dict[str, Any]]]:
    records: list[tuple[Path, dict[str, Any]]] = []
    for path in sorted(vault_root.rglob("metadata.json"), key=lambda item: item.as_posix().casefold()):
        relative_parts = path.relative_to(vault_root).parts
        if ".omnischolar" in relative_parts:
            continue
        try:
            document = _read_json(path)
        except (OSError, UnicodeError, json.JSONDecodeError, ValueError):
            continue
        if (
            document.get("schemaVersion") == 1
            and isinstance(document.get("publication"), dict)
            and isinstance(document.get("zotero"), dict)
        ):
            records.append((path.parent, document))
    return records


def _creator_names(value: Any) -> list[str]:
    if not isinstance(value, list):
        return []
    result: list[str] = []
    for creator in value:
        if not isinstance(creator, dict):
            continue
        name = str(creator.get("name") or "").strip()
        if not name:
            name = " ".join(
                part
                for key in ("firstName", "lastName")
                if (part := str(creator.get(key) or "").strip())
            )
        if name and name not in result:
            result.append(name)
    return result


def _source_tags(value: Any) -> list[str]:
    if not isinstance(value, list):
        return []
    result: list[str] = []
    for entry in value:
        tag = entry.get("tag") if isinstance(entry, dict) else entry
        if isinstance(tag, str) and tag.strip() and tag.strip() not in result:
            result.append(tag.strip())
    return result


def _obsidian_tag(value: str) -> str | None:
    tag = unicodedata.normalize("NFKC", value).strip().lstrip("#").strip()
    tag = re.sub(r"\s+", "-", tag)
    tag = re.sub(r"[^\w/-]+", "-", tag, flags=re.UNICODE)
    tag = re.sub(r"-{2,}", "-", tag).strip("-_/ ")
    if not tag:
        return None
    return f"tag-{tag}" if tag.isdecimal() else tag


def _dedupe(values: list[str]) -> list[str]:
    result: list[str] = []
    seen: set[str] = set()
    for value in values:
        text = unicodedata.normalize("NFKC", str(value)).strip()
        key = text.casefold()
        if text and key not in seen:
            seen.add(key)
            result.append(text)
    return result


def _prefixed_topics(tags: list[str], prefixes: tuple[str, ...]) -> list[str]:
    topics: list[str] = []
    for tag in tags:
        folded = tag.casefold()
        for prefix in prefixes:
            if folded.startswith(prefix.casefold()):
                topic = tag[len(prefix) :].strip(" /:-")
                if topic:
                    topics.append(topic)
                break
    return _dedupe(topics)


def _year(paper: dict[str, Any]) -> int | None:
    for value in (paper.get("year"), paper.get("date")):
        match = re.search(r"(?:19|20)\d{2}", str(value or ""))
        if match:
            return int(match.group(0))
    return None


def _mineru_markdown(directory: Path, index_name: str) -> tuple[Path, dict[str, Any]]:
    fallback: tuple[Path, dict[str, Any]] | None = None
    for path in sorted(directory.glob("*.md"), key=lambda item: item.name.casefold()):
        if path.name == index_name:
            continue
        properties = _frontmatter(path)
        if properties.get("recordType") == "mineru-publication":
            return path, properties
        fallback = fallback or (path, properties)
    if fallback is None:
        raise ValueError(f"No top-level MinerU Markdown found in {directory}")
    return fallback


def _zotero_record(directory: Path, index_name: str, mineru_path: Path) -> Path | None:
    for path in sorted(directory.rglob("*.md"), key=lambda item: item.as_posix().casefold()):
        if path == mineru_path or path.name == index_name:
            continue
        if _frontmatter(path).get("recordType") == "zotero-reading-record":
            return path
    return None


def _image_target(raw: str) -> str:
    target = raw.strip().strip("<>")
    if " \"" in target or " '" in target:
        target = target.split(" ", 1)[0]
    return unquote(target.split("#", 1)[0].split("?", 1)[0]).replace("\\", "/")


def _images(directory: Path, markdown_path: Path) -> list[str]:
    if markdown_path.stat().st_size > MAX_MARKDOWN_BYTES:
        raise ValueError(f"MinerU Markdown exceeds {MAX_MARKDOWN_BYTES} bytes: {markdown_path}")
    text = markdown_path.read_text(encoding="utf-8", errors="replace")
    candidates = [*STANDARD_IMAGE_RE.findall(text), *WIKI_IMAGE_RE.findall(text)]
    result: list[str] = []
    for raw in candidates:
        target = _image_target(raw)
        if not target or "://" in target:
            continue
        try:
            resolved = _confined(directory, target)
        except ValueError:
            continue
        if resolved.is_file() and resolved.suffix.casefold() in IMAGE_SUFFIXES:
            relative = resolved.relative_to(directory).as_posix()
            if relative not in result:
                result.append(relative)
    assets = directory / "assets"
    if assets.is_dir():
        for path in sorted(assets.rglob("*"), key=lambda item: item.as_posix().casefold()):
            if path.is_file() and path.suffix.casefold() in IMAGE_SUFFIXES:
                relative = path.relative_to(directory).as_posix()
                if relative not in result:
                    result.append(relative)
    return result


def _load_ai_topics(path: Path | None) -> dict[str, list[str]]:
    if path is None:
        return {}
    document = _read_json(path)
    result: dict[str, list[str]] = {}
    for key, value in document.items():
        if not isinstance(key, str) or not isinstance(value, list):
            raise ValueError("AI topic mappings must map string identifiers to string lists")
        topics = _dedupe([item for item in value if isinstance(item, str)])
        if len(topics) > 3:
            raise ValueError(f"AI topics for {key!r} exceed the maximum of three")
        result[key] = topics
    return result


def _ai_topics_for(
    mapping: dict[str, list[str]], paper: dict[str, Any], publication: dict[str, Any]
) -> list[str]:
    keys = (
        publication.get("id"),
        paper.get("zoteroKey"),
        paper.get("doi"),
        paper.get("DOI"),
        paper.get("title"),
    )
    for key in keys:
        if key is not None and str(key) in mapping:
            return mapping[str(key)]
    return []


def _callout(kind: str, title: str, content: str) -> list[str]:
    lines = [f"> [!{kind}]- {title}"]
    if not content.strip():
        return [*lines, "> _无内容。_"]
    for line in content.splitlines():
        lines.append(f"> {line}" if line else ">")
    return lines


def _safe_wiki_stem(value: str) -> str:
    text = unicodedata.normalize("NFC", re.sub(r"<[^>]*>", "", value))
    text = re.sub(r'[<>:"/\\|?*\x00-\x1f]+', " ", text)
    text = re.sub(r"\s+", " ", text).strip(" .") or "Untitled"
    if re.match(r"^(con|prn|aux|nul|com[1-9]|lpt[1-9])(?:\.|$)", text, re.IGNORECASE):
        text = f"_{text}"
    if len(text.encode("utf-8")) > 120:
        suffix = f"-{hashlib.sha256(text.encode('utf-8')).hexdigest()[:8]}"
        while text and len(f"{text}{suffix}".encode("utf-8")) > 120:
            text = text[:-1]
        text = f"{text.rstrip(' .-')}{suffix}"
    return text


def _topic_paths(topics_root: Path, topics: list[str]) -> dict[str, Path]:
    result: dict[str, Path] = {}
    occupied: dict[str, str] = {}
    for topic in sorted(topics, key=str.casefold):
        stem = _safe_wiki_stem(topic)
        key = stem.casefold()
        if key in occupied and occupied[key] != topic:
            suffix = hashlib.sha256(topic.encode("utf-8")).hexdigest()[:8]
            stem = f"{stem}-{suffix}"
            key = stem.casefold()
        occupied[key] = topic
        result[topic] = topics_root / f"{stem}.md"
    return result


