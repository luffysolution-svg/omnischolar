def _write_generated(path: Path, content: str, marker: str, *, force: bool = False) -> None:
    if path.exists():
        existing = path.read_text(encoding="utf-8", errors="replace")[:4096]
        if marker not in existing and not force:
            raise FileExistsError(f"Refusing to overwrite an unowned file: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    temporary.write_text(content, encoding="utf-8", newline="\n")
    os.replace(temporary, path)


def _check_generated_target(path: Path, marker: str, *, force: bool = False) -> None:
    if not path.exists() or force:
        return
    existing = path.read_text(encoding="utf-8", errors="replace")[:4096]
    if marker not in existing:
        raise FileExistsError(f"Refusing to overwrite an unowned file: {path}")


def build(
    vault_root: Path,
    *,
    base_relative: str,
    index_name: str,
    topic_prefixes: tuple[str, ...],
    ai_topics_path: Path | None,
    wiki: bool,
    wiki_index_relative: str,
    wiki_topics_relative: str,
    wiki_min_papers: int,
    force_base: bool,
    dry_run: bool,
) -> dict[str, Any]:
    root = vault_root.resolve()
    if not root.is_dir():
        raise ValueError(f"Vault root is not a directory: {root}")
    if Path(index_name).name != index_name or not index_name.lower().endswith(".md"):
        raise ValueError("--index-name must be a Markdown filename without directories")
    base_path = _confined(root, base_relative)
    if base_path.suffix.casefold() != ".base":
        raise ValueError("--base-path must end with .base")
    if wiki_min_papers < 1:
        raise ValueError("--wiki-min-papers must be at least 1")
    wiki_index_path = _confined(root, wiki_index_relative)
    if wiki and wiki_index_path.suffix.casefold() != ".md":
        raise ValueError("--wiki-index must end with .md")
    wiki_topics_root = _confined(root, wiki_topics_relative)
    if wiki and wiki_topics_root.exists() and not wiki_topics_root.is_dir():
        raise ValueError("--wiki-topics-dir must identify a directory")
    mapping = _load_ai_topics(ai_topics_path)
    records = _publication_sidecars(root)
    if not records:
        raise ValueError(f"No OmniScholar publication metadata found under {root}")

    plans: list[PaperPlan] = []
    topic_sources = {"zotero-tag": 0, "ai": 0, "missing": 0}
    without_images: list[str] = []
    without_topics: list[str] = []
    for directory, sidecar in records:
        paper = sidecar["zotero"]
        publication = sidecar["publication"]
        markdown_path, source_properties = _mineru_markdown(directory, index_name)
        zotero_record = _zotero_record(directory, index_name, markdown_path)
        images = _images(directory, markdown_path)
        raw_tags = _source_tags(paper.get("tags"))
        topics = _prefixed_topics(raw_tags, topic_prefixes)
        source = "zotero-tag"
        if not topics:
            topics = _ai_topics_for(mapping, paper, publication)
            source = "ai" if topics else "missing"
        topic_sources[source] += 1
        title = str(paper.get("title") or markdown_path.stem)
        if not images:
            without_images.append(title)
        if not topics:
            without_topics.append(title)
        plans.append(
            PaperPlan(
                directory=directory,
                sidecar=sidecar,
                markdown_path=markdown_path,
                source_properties=source_properties,
                zotero_record=zotero_record,
                images=images,
                topics=topics,
                topic_source=source,
                title=title,
                index_path=directory / index_name,
            )
        )

    topic_members: dict[str, list[PaperPlan]] = {}
    for plan in plans:
        for topic in plan.topics:
            topic_members.setdefault(topic, []).append(plan)
    shared_topics = {
        topic: members
        for topic, members in topic_members.items()
        if len(members) >= wiki_min_papers
    }
    topic_paths = _topic_paths(wiki_topics_root, list(shared_topics)) if wiki else {}

    planned: list[tuple[Path, str]] = []
    for plan in plans:
        topic_links = [
            f"[[{topic_paths[topic].relative_to(root).as_posix()}|{topic}]]"
            for topic in plan.topics
            if topic in topic_paths
        ]
        planned.append(
            (
                plan.index_path,
                _index_document(
                    plan.directory,
                    plan.sidecar,
                    plan.markdown_path,
                    plan.source_properties,
                    plan.zotero_record,
                    plan.images,
                    plan.topics,
                    plan.topic_source,
                    topic_links,
                ),
            )
        )

    wiki_documents: list[tuple[Path, str]] = []
    if wiki:
        wiki_documents.append(
            (
                wiki_index_path,
                _wiki_index_document(root, base_path, shared_topics, topic_paths, len(plans)),
            )
        )
        for topic, path in topic_paths.items():
            wiki_documents.append(
                (path, _topic_document(root, topic, shared_topics[topic], path))
            )

    all_generated_paths = [path for path, _ in (*planned, *wiki_documents)]
    if len(set(all_generated_paths)) != len(all_generated_paths):
        raise ValueError("Generated index and Wiki paths must be distinct")
    stale_wiki_pages: list[str] = []
    if wiki and wiki_topics_root.is_dir():
        expected = set(topic_paths.values())
        for path in sorted(wiki_topics_root.rglob("*.md"), key=lambda item: item.as_posix().casefold()):
            if path in expected:
                continue
            if MARKDOWN_MARKER in path.read_text(encoding="utf-8", errors="replace")[:4096]:
                stale_wiki_pages.append(path.relative_to(root).as_posix())

    if not dry_run:
        for path, _ in (*planned, *wiki_documents):
            _check_generated_target(path, MARKDOWN_MARKER)
        _check_generated_target(base_path, BASE_MARKER, force=force_base)
        for path, content in (*planned, *wiki_documents):
            _write_generated(path, content, MARKDOWN_MARKER)
        _write_generated(base_path, _base_document(), BASE_MARKER, force=force_base)
    return {
        "vaultRoot": str(root),
        "basePath": str(base_path),
        "papers": len(plans),
        "topicSources": topic_sources,
        "withoutTopics": without_topics,
        "withoutImages": without_images,
        "wiki": {
            "enabled": wiki,
            "indexPath": str(wiki_index_path) if wiki else None,
            "topicPages": len(topic_paths),
            "minimumPapers": wiki_min_papers,
            "staleTopicPages": stale_wiki_pages,
        },
        "dryRun": dry_run,
    }


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("vault_root", type=Path, help="Obsidian vault containing OmniScholar outputs")
    parser.add_argument("--base-path", default="Literature.base", help="Base path relative to vault")
    parser.add_argument("--index-name", default="literature-index.md", help="Generated index filename")
    parser.add_argument(
        "--topic-prefix",
        action="append",
        dest="topic_prefixes",
        help="Zotero topic tag prefix; repeat to supply several prefixes",
    )
    parser.add_argument("--ai-topics", type=Path, help="Optional JSON topic mapping")
    parser.add_argument(
        "--wiki",
        action="store_true",
        help="Generate a Wiki hub and shared-topic pages with preserved manual sections",
    )
    parser.add_argument(
        "--wiki-index",
        default="文献知识库.md",
        help="Wiki hub path relative to the vault",
    )
    parser.add_argument(
        "--wiki-topics-dir",
        default="Literature Wiki/Topics",
        help="Generated topic-page directory relative to the vault",
    )
    parser.add_argument(
        "--wiki-min-papers",
        type=int,
        default=2,
        help="Minimum papers sharing a topic before a Wiki page is generated",
    )
    parser.add_argument(
        "--force-base",
        action="store_true",
        help="Replace an existing unowned Base; requires explicit user authorization",
    )
    parser.add_argument("--dry-run", action="store_true", help="Inspect and report without writing")
    return parser


def main() -> int:
    args = _parser().parse_args()
    prefixes = tuple(args.topic_prefixes or DEFAULT_TOPIC_PREFIXES)
    try:
        summary = build(
            args.vault_root,
            base_relative=args.base_path,
            index_name=args.index_name,
            topic_prefixes=prefixes,
            ai_topics_path=args.ai_topics,
            wiki=args.wiki,
            wiki_index_relative=args.wiki_index,
            wiki_topics_relative=args.wiki_topics_dir,
            wiki_min_papers=args.wiki_min_papers,
            force_base=args.force_base,
            dry_run=args.dry_run,
        )
    except (OSError, UnicodeError, json.JSONDecodeError, ValueError, FileExistsError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
