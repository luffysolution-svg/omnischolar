def _manual_section(path: Path) -> str:
    if not path.is_file():
        return _default_manual_section()
    text = path.read_text(encoding="utf-8", errors="replace")
    start = text.find(MANUAL_START)
    end = text.find(MANUAL_END, start + len(MANUAL_START))
    if start < 0 or end < 0:
        return _default_manual_section()
    return text[start + len(MANUAL_START) : end].strip("\n")


def _paper_wikilink(vault_root: Path, plan: PaperPlan) -> str:
    relative = plan.index_path.relative_to(vault_root).as_posix()
    return f"[[{relative}|{plan.title}]]"


def _topic_document(vault_root: Path, topic: str, members: list[PaperPlan], path: Path) -> str:
    years = sorted(
        {year for plan in members if (year := _year(plan.sidecar["zotero"])) is not None}
    )
    year_range = None
    if years:
        year_range = str(years[0]) if len(years) == 1 else f"{years[0]}–{years[-1]}"
    existing_properties = _frontmatter(path) if path.is_file() else {}
    aliases = existing_properties.get("aliases")
    properties = {
        "recordType": "literature-topic",
        "generatedBy": GENERATED_BY,
        "topic": topic,
        "aliases": aliases if isinstance(aliases, list) else [],
        "paperCount": len(members),
        "yearRange": year_range,
        "reviewStatus": existing_properties.get("reviewStatus") or "draft",
    }
    frontmatter = yaml.safe_dump(
        properties,
        allow_unicode=True,
        default_flow_style=False,
        sort_keys=False,
        width=100_000,
    ).rstrip()
    related: list[str] = []
    ordered = sorted(
        members,
        key=lambda plan: (
            -(_year(plan.sidecar["zotero"]) or 0),
            plan.title.casefold(),
        ),
    )
    for plan in ordered:
        paper = plan.sidecar["zotero"]
        details = [str(value) for value in (_year(paper), paper.get("publicationTitle")) if value]
        suffix = f" — {', '.join(details)}" if details else ""
        related.append(f"- {_paper_wikilink(vault_root, plan)}{suffix}")
    return "\n".join(
        [
            "---",
            frontmatter,
            "---",
            GENERATED_COMMENT,
            "",
            f"# {topic}",
            "",
            MANUAL_START,
            _manual_section(path),
            MANUAL_END,
            "",
            AUTO_START,
            "## 相关文献",
            "",
            *related,
            AUTO_END,
            "",
        ]
    )


def _wiki_index_document(
    vault_root: Path,
    base_path: Path,
    topic_members: dict[str, list[PaperPlan]],
    topic_paths: dict[str, Path],
    paper_count: int,
) -> str:
    properties = {
        "recordType": "literature-wiki",
        "generatedBy": GENERATED_BY,
        "title": "文献知识库",
        "paperCount": paper_count,
        "topicCount": len(topic_paths),
    }
    frontmatter = yaml.safe_dump(
        properties,
        allow_unicode=True,
        default_flow_style=False,
        sort_keys=False,
        width=100_000,
    ).rstrip()
    base_relative = base_path.relative_to(vault_root).as_posix()
    topic_lines = [
        f"- [[{topic_paths[topic].relative_to(vault_root).as_posix()}|{topic}]]"
        f"（{len(topic_members[topic])} 篇）"
        for topic in sorted(topic_paths, key=str.casefold)
    ]
    return "\n".join(
        [
            "---",
            frontmatter,
            "---",
            GENERATED_COMMENT,
            "",
            "# 文献知识库",
            "",
            f"> [!info] 当前收录 {paper_count} 篇文献、{len(topic_paths)} 个共享主题。",
            "",
            "## 按主题浏览",
            "",
            f"![[{base_relative}#按主题]]",
            "",
            "## 文献总表",
            "",
            f"![[{base_relative}#文献总表]]",
            "",
            "## 主题词条",
            "",
            *(topic_lines or ["_暂时没有达到建页阈值的共享主题。_"]),
            "",
        ]
    )


def _index_document(
    directory: Path,
    sidecar: dict[str, Any],
    markdown_path: Path,
    source_properties: dict[str, Any],
    zotero_record: Path | None,
    images: list[str],
    topics: list[str],
    topic_source: str,
    topic_links: list[str],
) -> str:
    paper = sidecar["zotero"]
    publication = sidecar["publication"]
    title = str(paper.get("title") or source_properties.get("title") or "Untitled")
    authors = _creator_names(paper.get("creators"))
    raw_tags = _source_tags(paper.get("tags"))
    rendered_tags = source_properties.get("tags")
    tags = (
        _dedupe([str(item) for item in rendered_tags if isinstance(item, str)])
        if isinstance(rendered_tags, list)
        else _dedupe([tag for value in raw_tags if (tag := _obsidian_tag(value))])
    )
    zotero_key = str(paper.get("zoteroKey") or "")
    zotero_record_relative = (
        zotero_record.relative_to(directory).as_posix() if zotero_record is not None else None
    )
    properties: dict[str, Any] = {
        "recordType": "literature-index",
        "generatedBy": GENERATED_BY,
        "title": title,
        "authors": authors,
        "firstAuthor": authors[0] if authors else None,
        "year": _year(paper),
        "publicationTitle": paper.get("publicationTitle"),
        "topics": topics,
        "topicLinks": topic_links,
        "topicSource": topic_source,
        "tags": tags,
        "abstract": paper.get("abstract"),
        "cover": f"[[{images[0]}]]" if images else None,
        "imageCount": len(images),
        "mineruDocument": f"[[{markdown_path.name}]]",
        "zoteroRecord": f"[[{zotero_record_relative}]]" if zotero_record_relative else None,
        "zoteroLink": f"zotero://select/library/items/{zotero_key}" if zotero_key else None,
        "publicationId": publication.get("id"),
        "zoteroKey": zotero_key or None,
        "DOI": paper.get("doi") or paper.get("DOI"),
        "URL": paper.get("url") or paper.get("URL"),
    }
    frontmatter = yaml.safe_dump(
        properties,
        allow_unicode=True,
        default_flow_style=False,
        sort_keys=False,
        width=100_000,
    ).rstrip()
    source_lines = [f"- MinerU：[[{markdown_path.name}]]"]
    if zotero_record_relative:
        source_lines.append(f"- Zotero 笔记与批注：[[{zotero_record_relative}]]")
    if properties["zoteroLink"]:
        source_lines.append(f"- Zotero 条目：[打开]({properties['zoteroLink']})")
    gallery = "_MinerU 未输出可预览图片。_"
    if images:
        rows = [
            " ".join(f"![[{image}|240]]" for image in images[index : index + 3])
            for index in range(0, len(images), 3)
        ]
        gallery = "\n".join(rows)
    body = [
        "---",
        frontmatter,
        "---",
        GENERATED_COMMENT,
        "",
        f"# {title}",
        "",
        *(
            ["主题 Wiki：" + " · ".join(topic_links), ""]
            if topic_links
            else []
        ),
        *_callout("info", "来源", "\n".join(source_lines)),
        "",
        *_callout("abstract", "摘要", str(properties["abstract"] or "")),
        "",
        "## 图片画廊",
        "",
        *_callout("example", f"全部图片（{len(images)}）", gallery),
        "",
    ]
    return "\n".join(body)


def _record_filter() -> dict[str, Any]:
    return {"and": ['recordType == "literature-index"']}


